export function isBlockedCandidateDomain(
  domain: string,
  excludeMegaPublishers: boolean,
): boolean {
  const lower = domain.toLowerCase();
  if (NON_PROSPECT_DOMAINS.has(lower)) return true;
  if (excludeMegaPublishers && MEGA_PUBLISHER_DOMAINS.has(lower)) return true;
  if (lower.endsWith('.gov') || lower.endsWith('.edu') || lower.endsWith('.mil')) {
    return true;
  }
  return false;
}
